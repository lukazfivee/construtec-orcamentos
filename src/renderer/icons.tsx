/* Icones da interface (Phosphor, mesma familia do Centro e do Chamados). Os nomes seguem os que o app usava (lucide-react), cada um
   apontando para o equivalente Phosphor; troca-se o icone num lugar so. strokeWidth e aceito e ignorado (Phosphor nao tem traco variavel). */
import type { CSSProperties, ReactElement } from 'react';
import { Ph } from './Ph';

export type IconProps = { size?: number | string; className?: string; style?: CSSProperties; strokeWidth?: number | string; 'aria-hidden'?: boolean | 'true' | 'false'; 'aria-label'?: string; title?: string; color?: string };
export type LucideIcon = (props: IconProps) => ReactElement;

const make = (name: string): LucideIcon => function Icon({ size, className, color }: IconProps) {
  const px = typeof size === 'string' ? Number.parseFloat(size) : size;
  return <Ph name={name} size={px} color={color} className={className ? `pic ${className}` : 'pic'} />;
};

